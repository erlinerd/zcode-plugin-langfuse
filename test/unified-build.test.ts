import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const npmCommand = process.platform === "win32" ? "npm.cmd" : "npm";
const layoutRoot = join(repoRoot, "artifacts", "plugin-layout");
const pluginLayoutRoot = join(layoutRoot, "plugins", "zcode-plugin-langfuse");

function packagePlugin() {
  execFileSync(npmCommand, ["run", "package:plugin"], {
    cwd: repoRoot,
    encoding: "utf8",
    stdio: "pipe",
  });
}

function buildLayout(outputRoot: string) {
  execFileSync(
    process.execPath,
    ["scripts/build-layout.mjs", "--output-root", outputRoot],
    {
      cwd: repoRoot,
      encoding: "utf8",
      stdio: "pipe",
    },
  );
}

describe("unified plugin package", () => {
  it("creates the release archive and plugin catalog layout together", () => {
    packagePlugin();

    expect(existsSync(join(repoRoot, "artifacts", "plugin.zip"))).toBe(true);
    expect(existsSync(join(repoRoot, "artifacts", "plugin.zip.sha256"))).toBe(
      true,
    );

    const expectedFiles = [
      ".zcode-plugin/plugin.json",
      "hooks/hooks.json",
      "dist/hooks/entry.mjs",
      "package.json",
      "README.md",
      "README_CN.md",
      "LICENSE",
      "THIRD_PARTY_NOTICES.md",
    ];
    for (const relativePath of expectedFiles) {
      expect(existsSync(join(pluginLayoutRoot, relativePath))).toBe(true);
    }

    const entry = JSON.parse(
      readFileSync(join(layoutRoot, "marketplace-entry.json"), "utf8"),
    ) as {
      name: string;
      source: string;
      version: string;
      category: string;
    };
    expect(entry).toMatchObject({
      name: "zcode-plugin-langfuse",
      source: "./plugins/zcode-plugin-langfuse",
      version: "0.2.0",
      category: "developer-tools",
    });

    const bundle = readFileSync(
      join(pluginLayoutRoot, "dist/hooks/entry.mjs"),
      "utf8",
    );
    expect(bundle).toContain("Generated by npm run build");
    expect(bundle).toBe(
      readFileSync(join(repoRoot, "dist/hooks/entry.mjs"), "utf8"),
    );
  });

  it("rejects a layout output path outside the generated artifacts directory", () => {
    expect(() => buildLayout(join(repoRoot, "src"))).toThrow(/artifacts/);
  });

  it("removes stale plugin layout files on a repeated build", () => {
    const stalePath = join(pluginLayoutRoot, "stale-from-previous-build.txt");
    writeFileSync(stalePath, "stale\n");

    packagePlugin();

    expect(existsSync(stalePath)).toBe(false);
  });
});
